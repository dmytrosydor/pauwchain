"""Generates docs/vectors.json, the shared test vectors for Python and C++ (docs/contract.md).

The vectors are committed; tests in both languages read the same file. Regenerate only when the contract changes:
python scripts/gen_vectors.py
"""
import hashlib
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch  # noqa: E402

from worker.canonical import block_header_bytes, canonical_weight_hash, derive_seed  # noqa: E402
from worker.train import ckpt_root  # noqa: E402

U32, U64, I64_MIN, I64_MAX = 2**32 - 1, 2**64 - 1, -(2**63), 2**63 - 1


def rand_hash(rng):
    return bytes(rng.getrandbits(8) for _ in range(32)).hex()


def header(rng, **over):
    h = {
        "version": rng.choice([1, 2, U32]), "height": rng.randrange(U64), "prev_hash": rand_hash(rng),
        "task_id": rand_hash(rng), "round": rng.randrange(U64), "miner_id": rand_hash(rng),
        "timestamp": rng.randrange(U64), "w_start": rand_hash(rng), "w_end": rand_hash(rng),
        "ckpt_root": rand_hash(rng), "K": rng.randrange(U32), "k": rng.randrange(1, U32),
        "metric_micro": rng.randrange(I64_MIN, I64_MAX),
    }
    h.update(over)
    if h["version"] >= 2:  # version 2 headers also carry tx_root
        h["tx_root"] = rand_hash(rng)
    return h


def main() -> None:
    rng = random.Random(20261027)
    out = {"comment": "generated by scripts/gen_vectors.py; do not edit by hand"}

    heads = [header(rng) for _ in range(40)]
    heads.append(header(rng, version=0, height=0, round=0, timestamp=0, K=0, k=0, metric_micro=0))
    heads.append(header(rng, height=U64, round=U64, timestamp=U64, K=U32, k=U32, metric_micro=I64_MAX))
    heads.append(header(rng, metric_micro=I64_MIN))
    heads.append(header(rng, metric_micro=-1))
    out["headers"] = []
    for h in heads:
        raw = block_header_bytes(h)
        out["headers"].append({"header": h, "bytes_hex": raw.hex(), "block_hash": hashlib.sha256(raw).hexdigest()})

    out["ckpt_roots"] = []
    for m in (0, 1, 2, 20):
        hs = [bytes.fromhex(rand_hash(rng)) for _ in range(m + 1)]
        out["ckpt_roots"].append({"hashes": [h.hex() for h in hs], "root": ckpt_root(hs).hex()})

    out["seeds"] = []
    for rnd in (0, 1, 7, U64):
        prev, miner = rand_hash(rng), rand_hash(rng)
        out["seeds"].append({"prev_block_hash": prev, "miner_id": miner, "round": rnd,
                             "seed": derive_seed(bytes.fromhex(prev), bytes.fromhex(miner), rnd)})

    cases = [
        {"w": ([0.0, -0.0, 1.0, -1.5], (2, 2))},
        {"b": ([float("nan"), float("inf"), float("-inf")], (3,))},
        {"scalar": ([3.25], ())},
        {"tiny": ([1e-45, -1e-45, 1.17549435e-38], (3,))},  # denormals and the smallest normal
        {"z.weight": ([0.5] * 6, (1, 2, 3)), "a.bias": ([2.0, -2.0], (2,))},  # ordering by name
    ]
    out["weights"] = []
    for case in cases:
        state = {n: torch.tensor(v, dtype=torch.float32).reshape(shape) for n, (v, shape) in case.items()}
        enc = {n: {"shape": list(t.shape), "le_hex": t.contiguous().numpy().tobytes().hex()}
               for n, t in state.items()}
        out["weights"].append({"tensors": enc, "hash": canonical_weight_hash(state).hex()})

    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "vectors.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=1)
    print(f"{len(out['headers'])} headers, {len(out['ckpt_roots'])} roots, {len(out['seeds'])} seeds, "
          f"{len(out['weights'])} weight cases → {path}")


if __name__ == "__main__":
    main()
